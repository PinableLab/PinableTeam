#!/usr/bin/env python3
"""Run the Work HTTP + SQLite + Desktop probe contract against a Desktop checkout.

Usage: python3 scripts/test-desktop-probe.py ../PinableDesktop
Requires the normal Work test environment, including web/native-chat
(generated by scripts/build-chatbot.sh). The test uses no network listeners.
"""

import argparse
import json
import os
import sys
from pathlib import Path
import subprocess
import tempfile

WORK = Path(__file__).resolve().parents[1]
FIXTURE = WORK / "scripts/testdata/desktop-probe"

parser = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("desktop_checkout", type=Path, help="PinableDesktop repository root")
args = parser.parse_args()
bridge = args.desktop_checkout.resolve() / "pinable-desktop/internal/services/workbridge"
sources = sorted(path for path in bridge.glob("*.go") if not path.name.endswith("_test.go"))
if not sources:
    parser.error(f"Desktop workbridge Go source not found in {bridge}")

# Overlay the checked-out client as a test-only package and the fixture as a
# Work HTTP API test. The regular package build and both go.mod files stay intact.
overlay = {str(FIXTURE / path.name): str(path) for path in sources}
overlay[str(WORK / "internal/httpapi/cross_repository_desktop_probe_test.go")] = str(
    FIXTURE / "contract_test.go.in"
)
with tempfile.TemporaryDirectory(prefix="desktop-probe-test-") as tmp:
    overlay_path = Path(tmp) / "overlay.json"
    overlay_path.write_text(json.dumps({"Replace": overlay}), encoding="utf-8")
    env = {**os.environ, "PWD": str(WORK)}
    command = [
        "go", "test", "-json", "-mod=readonly", f"-overlay={overlay_path}",
        "-count=1", "-v", "-run", "^TestCrossRepositoryDesktopProbe$", "./internal/httpapi",
    ]
    passed = False
    with subprocess.Popen(command, cwd=WORK, env=env, stdout=subprocess.PIPE, text=True) as process:
        for line in process.stdout:
            event = json.loads(line)
            if event.get("Output"):
                print(event["Output"], end="", flush=True)
            if event.get("Action") == "pass" and event.get("Test") == "TestCrossRepositoryDesktopProbe":
                passed = True
        code = process.wait()
if code == 0 and not passed:
    sys.exit("The cross-repository test did not run.")
raise SystemExit(code)
